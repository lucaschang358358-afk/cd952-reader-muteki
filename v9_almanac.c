const char *almanac_radar_archetype(const int s[5]) {
    /* 0=專注時長, 1=翻頁速度, 2=打卡毅力, 3=藏書廣度, 4=完食率 */
    int avg = (s[0] + s[1] + s[2] + s[3] + s[4]) / 5;
    if (avg >= 85) return "全能傳奇大賢者";
    int best = 0;
    for (int i = 1; i < 5; i++) if (s[i] > s[best]) best = i;
    if (s[best] < 20) return "初入書海的新星";
    switch (best) {
        case 0: return "深度沉浸思辨家";
        case 1: return "一目十行速讀王";
        case 2: return "風雨無阻打卡神";
        case 3: return "博覽群書收藏家";
        default: return "有始有終完食達人";
    }
}

